import type { ActProject } from '../core/project/model.ts';
import { SILICON_REVISION } from '../core/project/model.ts';
import type { Json } from '../core/registry/types.ts';
import { builtins } from '../core/registry/registry.ts';
import type { Selector } from '../core/graph/selectors.ts';
import { formatMatch } from '../core/graph/selectors.ts';
import { validateProject } from '../core/validation/project.ts';
import { scriptOutputNames } from '../core/project/script-outputs.ts';

export function pythonLiteral(value: Json): string {
  if (value === null) return 'None';
  if (typeof value === 'boolean') return value ? 'True' : 'False';
  if (typeof value === 'number') { if (!Number.isFinite(value)) throw new Error('Nonfinite Python literal'); return String(value); }
  if (typeof value === 'string') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(pythonLiteral).join(', ')}]`;
  return `{${Object.entries(value).map(([key, item]) => `${pythonLiteral(key)}: ${pythonLiteral(item)}`).join(', ')}}`;
}
const keywords = new Set('False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield match case'.split(' '));
function identifier(name: string): string {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) || keywords.has(name)) throw new Error(`Invalid Python identifier: ${name}`);
  return name;
}
/** A single generator serves .py export and the local Python worker. No project data is evaluated here. */
export function exportPython(project: ActProject): string {
  const registry = builtins();
  const errors = validateProject(project, registry).filter(issue => issue.severity === 'error');
  if (errors.length) throw new Error(errors.map(issue => issue.message).join('; '));
  if (project.siliconRevision !== SILICON_REVISION) throw new Error('Upgrade this Act to the supported Silicon revision before running/exporting.');
  if (Object.keys(project.sourceModules).length || Object.keys(project.assets).length) throw new Error('Single-file Python export does not yet support additional source modules or binary assets. Save .act to preserve them.');
  for (const script of Object.values(project.scripts)) {
    if (script.draft) throw new Error(`Check Python in “${script.name}” before running or exporting. Its latest draft is saved in .act.`);
    if (!['handler', 'startup', 'lifecycle', 'trigger'].includes(script.role)) throw new Error(`Unsupported script role: ${script.role}. Save .act to preserve it.`);
  }
  const definition = (typeId: string) => {
    const def = project.definitions[typeId] ?? registry.get(typeId);
    if (!def || def.provider !== 'silicon' || def.module !== 'silicon') throw new Error(`Python export requires a supported Silicon component: ${typeId}`);
    return def;
  };
  const type = (typeId: string) => `_silicon.${identifier(definition(typeId).name)}`;
  const ref = (id: string) => id === project.game.id ? 'game' : `game[components[${pythonLiteral(id)}]]`;
  const select = (selector: Selector) => {
    let result = ref(selector.root);
    for (const segment of selector.path) {
      const match = formatMatch(segment.match);
      result += `[${type(segment.typeId)}${match === null ? '' : `:${pythonLiteral(match)}`}]`;
    }
    // TriggerCall works on live selections; .component would discard the game binding.
    return result;
  };
  const lines = ['# Generated by Actwright. Save the editable project as .act.', `# Silicon revision: ${SILICON_REVISION}`, 'import asyncio', 'import ast', 'import linecache', 'import silicon as _silicon', '', '',
    'def _bound_parent(game, parent, default):',
    '    value = default if parent is None else parent',
    '    return game[value] if isinstance(value, _silicon.Component) else value', '', '',
    'def _component_factories(game):',
    '    def resolve(component_type):',
    '        if isinstance(component_type, str):',
    '            name = component_type.removeprefix("silicon.")',
    '            component_type = getattr(_silicon, name, None)',
    '        if not isinstance(component_type, type) or not issubclass(component_type, _silicon.Component):',
    '            raise ValueError("Expected a Silicon component type")',
    '        return component_type',
    '    def new_instance(component_type, component_id, parent=None, *args, **kwargs):',
    '        if not isinstance(component_id, str) or not component_id or any(c in component_id for c in ",#*?!"):',
    '            raise ValueError("Component ID must be a nonempty literal ID without selector characters")',
    '        instance = resolve(component_type)(*args, **kwargs)',
    '        destination = _bound_parent(game, parent, game)',
    '        destination[instance:component_id]',
    '        return game[instance]',
    '    def new_singleton(component_type, parent=None, *args, **kwargs):',
    '        instance = resolve(component_type)(*args, **kwargs)',
    '        destination = _bound_parent(game, parent, game)',
    '        destination[instance]',
    '        return game[instance]',
    '    return new_instance, new_singleton', '', '',
    'def _script_payload(self, *args, **kwargs):',
    '    pass', '', '',
    'class _ScriptOutputs(_silicon.Component):',
    '    def __component__(self, names):',
    '        self._slots["out"] = {name: _script_payload for name in names}', '', '',
    'class _CallableInput(_silicon.Component):',
    '    def __component__(self):',
    '        self.callback = None',
    '    @_silicon.input',
    '    def run(self, *args, **kwargs):',
    '        return self.callback(*args, **kwargs)', '', '',
    'def _connect_callable(game, source, callback):',
    '    component = _CallableInput()',
    '    component.callback = callback',
    '    bridge = game[game.add(component)]',
    '    source >> bridge.ins.run', '', '',
    'def _make_emitter(outputs):',
    '    def emit(name, *args, **kwargs):',
    '        if name not in outputs.component._slots["out"]:',
    '            raise ValueError(f"Unknown script output: {name}. Use a constant name in an Output block or emit() call.")',
    '        return getattr(outputs.out, name)(*args, **kwargs)',
    '    return emit', '', '',
    'def _make_callback(source, filename, scope, parameters):',
    '    # Compile the original body directly: indentation inside multiline strings stays exact.',
    '    tree = ast.parse(source or "pass", filename=filename)',
    '    names = ["game", "component", "parent", *parameters]',
    '    arguments = ast.arguments(posonlyargs=[], args=[ast.arg(arg=name) for name in names],',
    '                              kwonlyargs=[], kw_defaults=[], defaults=[ast.Constant(None) for _ in names[1:]],',
    '                              kwarg=ast.arg(arg="context"))',
    '    context = ast.parse("parent = _bound_parent(game, parent, _script_parent)").body',
    '    function = ast.FunctionDef(name="_handler", args=arguments, body=context + tree.body, decorator_list=[])',
    '    module = ast.fix_missing_locations(ast.Module(body=[function], type_ignores=[]))',
    '    linecache.cache[filename] = (len(source), None, source.splitlines(True), filename)',
    '    namespace = {**globals(), **scope}',
    '    exec(compile(module, filename, "exec"), namespace)',
    '    return namespace["_handler"]', '', ''];
  lines.push('', '', 'def build_game():',
    `    game = _silicon.Game(${pythonLiteral(project.name)}, seed=${pythonLiteral(project.game.seed)}, tick_rate=${pythonLiteral(project.game.tickRate)})`, '    components = {}', '    script_outputs = {}');
  const emit = (line: string) => lines.push(`    ${line}`);
  emit('new_instance, new_singleton = _component_factories(game)');
  for (const id of project.game.order) {
    const instance = project.instances[id]!, def = definition(instance.typeId);
    const positional: string[] = [], named: string[] = [];
    const known = new Set<string>();
    for (const parameter of def.constructor.parameters) {
      known.add(parameter.name);
      const value = instance.config[parameter.name];
      if (parameter.kind === 'positionalOnly') {
        if (value !== undefined) positional.push(pythonLiteral(value));
        else if (parameter.default.kind === 'literal') positional.push(pythonLiteral(parameter.default.value));
        else throw new Error(`Missing positional argument ${parameter.name}`);
      } else if (parameter.kind === 'varPositional') {
        if (value !== undefined) { if (!Array.isArray(value)) throw new Error(`${parameter.name} must be a list`); positional.push(...value.map(pythonLiteral)); }
      } else if (parameter.kind === 'varKeyword') {
        if (value !== undefined) { if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error(`${parameter.name} must be an object`); named.push(`**${pythonLiteral(value)}`); }
      } else if (value !== undefined) named.push(`${identifier(parameter.name)}=${pythonLiteral(value)}`);
    }
    for (const key of Object.keys(instance.config)) if (!known.has(key)) throw new Error(`Unknown constructor argument ${def.name}.${key}`);
    const variable = `components[${pythonLiteral(id)}]`;
    emit(`${variable} = ${type(instance.typeId)}(${[...positional, ...named].join(', ')})`);
    const location = project.locations.find(entry => entry.componentId === id && entry.kind === 'canonical')!;
    if (instance.construction.kind === 'add') emit(`game.add(${variable}, id=${pythonLiteral(instance.construction.runtimeId)})`);
    else emit(`${ref(location.parentId)}[${variable}${location.singleton ? '' : `:${pythonLiteral(location.aliases.join(','))}`}]`);
    for (const [key, value] of Object.entries(instance.state)) emit(`setattr(${ref(id)}.state, ${pythonLiteral(key)}, ${pythonLiteral(value)})`);
  }
  for (const location of project.locations.filter(entry => entry.kind === 'link')) emit(`${ref(location.parentId)}[${type(project.instances[location.componentId]!.typeId)}${location.singleton ? '' : `:${pythonLiteral(location.aliases.join(','))}`}] = ${ref(location.componentId)}`);
  Object.values(project.scripts).forEach(script => {
    emit(`script_outputs[${pythonLiteral(script.id)}] = game[game.add(_ScriptOutputs(${pythonLiteral(scriptOutputNames(project, script.id))}))]`);
  });
  const scriptNames = new Map<string, string>();
  Object.values(project.scripts).forEach((script, index) => {
    const name = `_script_${index}`; scriptNames.set(script.id, name);
    emit(''); emit(`# ${script.name.replace(/[\r\n]/g, ' ')}`);
    const parameters = script.parameters.filter(parameter => !['game', 'component', 'parent', 'context'].includes(parameter.name)).map(parameter => identifier(parameter.name));
    if (new Set(parameters).size !== parameters.length) throw new Error('Duplicate callback parameters');
    emit(`${name} = _make_callback(${pythonLiteral(script.synchronizedSource)}, ${pythonLiteral(`script_${script.id}.py`)},`);
    const parentId = project.locations.find(location => location.kind === 'canonical' && location.componentId === script.ownerId)?.parentId ?? project.game.id;
    emit(`    {"new_instance": new_instance, "new_singleton": new_singleton, "game": game, "components": components, "self": ${ref(script.ownerId)}, "_script_parent": ${ref(parentId)}, "emit": _make_emitter(script_outputs[${pythonLiteral(script.id)}])}, ${pythonLiteral(parameters)})`);
  });
  const wired = new Set<string>();
  for (const edge of project.slotEdges.filter(edge => edge.enabled)) {
    const sourceMember = project.instances[edge.sourceId] && definition(project.instances[edge.sourceId]!.typeId).members.find(member => member.name === edge.output && member.kind === 'trigger');
    const targetMember = project.instances[edge.targetId] && definition(project.instances[edge.targetId]!.typeId).members.find(member => member.name === edge.input && member.kind === 'trigger');
    const source = project.scripts[edge.sourceId] ? `getattr(script_outputs[${pythonLiteral(edge.sourceId)}].out, ${pythonLiteral(edge.output)})`
      : edge.sourceId === project.game.id || sourceMember ? `getattr(${ref(edge.sourceId)}, ${pythonLiteral(edge.output)})`
      : `getattr(${ref(edge.sourceId)}.out, ${pythonLiteral(edge.output)})`;
    const target = project.scripts[edge.targetId] ? scriptNames.get(edge.targetId)!
      : targetMember ? `getattr(${ref(edge.targetId)}, ${pythonLiteral(edge.input)})`
      : `getattr(${ref(edge.targetId)}.ins, ${pythonLiteral(edge.input)})`;
    if (project.scripts[edge.targetId]) wired.add(edge.targetId);
    if (edge.sourceId !== project.game.id && !sourceMember && (project.scripts[edge.targetId] || targetMember)) {
      if (project.scripts[edge.targetId]) {
        const sourceComponent = project.instances[edge.sourceId] ? ref(edge.sourceId) : 'None';
        emit(`_connect_callable(game, ${source}, lambda *args, **kwargs: ${target}(game, ${sourceComponent}, None, *args, **kwargs))`);
      } else emit(`_connect_callable(game, ${source}, ${target})`);
    } else if (!project.scripts[edge.targetId] && !targetMember && (edge.sourceId === project.game.id || sourceMember)) {
      const input = definition(project.instances[edge.targetId]!.typeId).members.find(member => member.name === edge.input && member.kind === 'input')!;
      const names = input.parameters.filter(parameter => !parameter.kind.startsWith('var')).map(parameter => parameter.name);
      emit(`${source} >> (lambda **context: ${target}(**{key: value for key, value in context.items() if key in ${pythonLiteral(names)}}))`);
    } else emit(`${source} >> ${target}`);
  }

  for (const rule of project.triggerRules) {
    const source = rule.source.kind === 'game' ? `game.${rule.source.member}` : `${select(rule.source.selector)}.${identifier(rule.source.member)}`;
    const targets = rule.targets.map(target => {
      if (target.kind === 'script') { wired.add(target.scriptId); return scriptNames.get(target.scriptId)!; }
      return `${select(target.selector)}.${identifier(target.member)}`;
    });
    if (targets.length) emit(`${source} >> [${targets.join(', ')}]`);
  }
  for (const script of Object.values(project.scripts)) {
    if (wired.has(script.id)) continue;
    if (script.role === 'startup') emit(`game.start >> ${scriptNames.get(script.id)}`);
    else throw new Error(`Script “${script.name}” is not connected to an event.`);
  }
  emit('game.actwright_components = components'); emit('return game');
  lines.push('', '', 'async def main():', '    game = build_game()', '    try:', '        await game.run()', '    finally:', '        game.stop()', '', '', 'if __name__ == "__main__":', '    try:', '        asyncio.run(main())', '    except KeyboardInterrupt:', '        pass', '');
  return lines.join('\n');
}
